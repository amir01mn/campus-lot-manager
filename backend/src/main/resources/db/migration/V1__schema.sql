-- Campus Parking: full schema.
-- Conventions: timestamps are timestamptz, money is numeric(10,2) (CAD), enums are varchar + CHECK.

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            uuid         PRIMARY KEY,
    email         varchar(254) NOT NULL,
    password_hash varchar(100) NOT NULL,
    first_name    varchar(100) NOT NULL,
    last_name     varchar(100) NOT NULL,
    user_type     varchar(20)  NOT NULL,
    role          varchar(20)  NOT NULL,
    created_at    timestamptz  NOT NULL,
    version       bigint       NOT NULL DEFAULT 0,
    CONSTRAINT uq_users_email UNIQUE (email),
    -- emails are stored normalised so a plain unique constraint is case-insensitive
    CONSTRAINT ck_users_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_users_user_type CHECK (user_type IN ('STUDENT', 'FACULTY', 'STAFF', 'VISITOR')),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'MANAGER', 'SUPER_MANAGER'))
);

CREATE INDEX ix_users_role ON users (role);

-- Reference data: e-mail -> pricing tier (the "YU database" of the original project).
CREATE TABLE university_directory (
    email     varchar(254) PRIMARY KEY,
    user_type varchar(20)  NOT NULL,
    CONSTRAINT ck_directory_email_lower CHECK (email = lower(email)),
    CONSTRAINT ck_directory_user_type CHECK (user_type IN ('STUDENT', 'FACULTY', 'STAFF'))
);

-- ---------------------------------------------------------------------------
-- Lots and spots
-- ---------------------------------------------------------------------------
CREATE TABLE parking_lots (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(100) NOT NULL,
    location   varchar(200) NOT NULL,
    enabled    boolean      NOT NULL DEFAULT true,
    created_at timestamptz  NOT NULL,
    version    bigint       NOT NULL DEFAULT 0,
    CONSTRAINT uq_parking_lots_name UNIQUE (name)
);

CREATE TABLE parking_spots (
    id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id               bigint      NOT NULL REFERENCES parking_lots (id),
    label                varchar(20) NOT NULL,
    sensor_id            varchar(50) NOT NULL,
    -- manager-controlled state
    enabled              boolean     NOT NULL DEFAULT true,
    maintenance_required boolean     NOT NULL DEFAULT false,
    -- sensor-driven state (never touches the manager fields)
    occupied             boolean     NOT NULL DEFAULT false,
    last_sensor_update   timestamptz,
    version              bigint      NOT NULL DEFAULT 0,
    CONSTRAINT uq_parking_spots_sensor_id UNIQUE (sensor_id),
    CONSTRAINT uq_parking_spots_lot_label UNIQUE (lot_id, label)
);

-- ---------------------------------------------------------------------------
-- Bookings
-- ---------------------------------------------------------------------------
CREATE TABLE bookings (
    id             uuid          PRIMARY KEY,
    reference_code varchar(12)   NOT NULL,
    user_id        uuid          NOT NULL REFERENCES users (id),
    spot_id        bigint        NOT NULL REFERENCES parking_spots (id),
    licence_plate  varchar(10)   NOT NULL,
    start_time     timestamptz   NOT NULL,
    end_time       timestamptz   NOT NULL,
    status         varchar(20)   NOT NULL,
    payment_method varchar(20)   NOT NULL,
    hourly_rate    numeric(10,2) NOT NULL,
    deposit_amount numeric(10,2) NOT NULL,
    total_amount   numeric(10,2) NOT NULL,
    created_at     timestamptz   NOT NULL,
    cancelled_at   timestamptz,
    completed_at   timestamptz,
    version        bigint        NOT NULL DEFAULT 0,
    CONSTRAINT uq_bookings_reference_code UNIQUE (reference_code),
    CONSTRAINT ck_bookings_reference_code CHECK (reference_code ~ '^CP-[A-Z0-9]{6}$'),
    CONSTRAINT ck_bookings_licence_plate CHECK (licence_plate ~ '^[A-Z0-9 -]{2,10}$'),
    CONSTRAINT ck_bookings_time_range CHECK (end_time > start_time),
    CONSTRAINT ck_bookings_status CHECK (status IN ('CONFIRMED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_bookings_payment_method CHECK (payment_method IN ('CREDIT_CARD', 'DEBIT_CARD', 'PAYPAL')),
    CONSTRAINT ck_bookings_hourly_rate CHECK (hourly_rate > 0),
    CONSTRAINT ck_bookings_deposit_amount CHECK (deposit_amount >= 0),
    CONSTRAINT ck_bookings_total_amount CHECK (total_amount >= 0),
    -- No two CONFIRMED bookings may overlap on the same spot (half-open [start, end)).
    CONSTRAINT ex_bookings_spot_no_overlap
        EXCLUDE USING gist (spot_id WITH =, tstzrange(start_time, end_time, '[)') WITH &&)
        WHERE (status = 'CONFIRMED'),
    -- Defence in depth for "a user may not hold two overlapping CONFIRMED bookings".
    CONSTRAINT ex_bookings_user_no_overlap
        EXCLUDE USING gist (user_id WITH =, tstzrange(start_time, end_time, '[)') WITH &&)
        WHERE (status = 'CONFIRMED')
);

CREATE INDEX ix_bookings_user_start ON bookings (user_id, start_time DESC);
CREATE INDEX ix_bookings_spot_start ON bookings (spot_id, start_time);
CREATE INDEX ix_bookings_status_end ON bookings (status, end_time);
CREATE INDEX ix_bookings_start ON bookings (start_time);

-- ---------------------------------------------------------------------------
-- Payments
-- ---------------------------------------------------------------------------
CREATE TABLE payments (
    id                 uuid          PRIMARY KEY,
    booking_id         uuid          NOT NULL REFERENCES bookings (id),
    type               varchar(20)   NOT NULL,
    amount             numeric(10,2) NOT NULL,
    method             varchar(20)   NOT NULL,
    status             varchar(20)   NOT NULL,
    provider_reference varchar(100),
    created_at         timestamptz   NOT NULL,
    CONSTRAINT ck_payments_type CHECK (type IN ('DEPOSIT', 'FINAL', 'REFUND')),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_method CHECK (method IN ('CREDIT_CARD', 'DEBIT_CARD', 'PAYPAL')),
    CONSTRAINT ck_payments_status CHECK (status IN ('SUCCEEDED', 'FAILED'))
);

CREATE INDEX ix_payments_booking ON payments (booking_id, created_at);
CREATE INDEX ix_payments_created_at ON payments (created_at);

-- ---------------------------------------------------------------------------
-- Notifications
-- ---------------------------------------------------------------------------
CREATE TABLE notifications (
    id           uuid         PRIMARY KEY,
    recipient_id uuid         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         varchar(40)  NOT NULL,
    message      varchar(500) NOT NULL,
    is_read      boolean      NOT NULL DEFAULT false,
    booking_id   uuid         REFERENCES bookings (id) ON DELETE SET NULL,
    spot_id      bigint       REFERENCES parking_spots (id) ON DELETE SET NULL,
    created_at   timestamptz  NOT NULL,
    CONSTRAINT ck_notifications_type CHECK (type IN (
        'BOOKING_CONFIRMED', 'BOOKING_CANCELLED', 'BOOKING_EXTENDED', 'BOOKING_COMPLETED',
        'OVERSTAY_DETECTED', 'UNAUTHORIZED_PARKING', 'MAINTENANCE_FLAGGED'))
);

CREATE INDEX ix_notifications_recipient_created ON notifications (recipient_id, created_at DESC);
CREATE INDEX ix_notifications_recipient_unread ON notifications (recipient_id) WHERE is_read = false;
CREATE INDEX ix_notifications_booking ON notifications (booking_id);
CREATE INDEX ix_notifications_spot ON notifications (spot_id);
